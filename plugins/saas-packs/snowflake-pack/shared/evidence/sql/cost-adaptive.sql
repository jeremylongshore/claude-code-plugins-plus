-- Adaptive Warehouse per-query credits for one settled half-open UTC window.
-- Compute is attribution beneath warehouse compute; cloud services remain context.
WITH usage_rows AS (
  SELECT
    CONCAT(COALESCE(TO_VARCHAR(QUERY_ID), ''), '|', TO_VARCHAR(QUERY_METERING_HOUR)) AS SORT_KEY,
    OBJECT_CONSTRUCT_KEEP_NULL(
      '_dataset', 'adaptive_usage',
      'start_time', QUERY_METERING_HOUR,
      'end_time', DATEADD('hour', 1, QUERY_METERING_HOUR),
      'query_id_sha256', SHA2(TO_JSON(ARRAY_CONSTRUCT(CURRENT_ORGANIZATION_NAME(), CURRENT_ACCOUNT_NAME(), QUERY_ID)), 256),
      'warehouse_id', WAREHOUSE_ID,
      'warehouse_name_sha256', IFF(WAREHOUSE_NAME IS NULL, NULL, SHA2(TO_JSON(ARRAY_CONSTRUCT(CURRENT_ORGANIZATION_NAME(), CURRENT_ACCOUNT_NAME(), WAREHOUSE_NAME)), 256)),
      'query_hash', IFF(QUERY_HASH IS NULL, NULL, SHA2(TO_JSON(ARRAY_CONSTRUCT(CURRENT_ORGANIZATION_NAME(), CURRENT_ACCOUNT_NAME(), QUERY_HASH)), 256)),
      'query_parameterized_hash', IFF(QUERY_PARAMETERIZED_HASH IS NULL, NULL, SHA2(TO_JSON(ARRAY_CONSTRUCT(CURRENT_ORGANIZATION_NAME(), CURRENT_ACCOUNT_NAME(), QUERY_PARAMETERIZED_HASH)), 256)),
      'query_tag_sha256', IFF(QUERY_TAG IS NULL OR QUERY_TAG = '', NULL, SHA2(TO_JSON(ARRAY_CONSTRUCT(CURRENT_ORGANIZATION_NAME(), CURRENT_ACCOUNT_NAME(), QUERY_TAG)), 256)),
      'query_tag_present', QUERY_TAG IS NOT NULL AND QUERY_TAG <> '',
      'user_name_sha256', IFF(USER_NAME IS NULL, NULL, SHA2(TO_JSON(ARRAY_CONSTRUCT(CURRENT_ORGANIZATION_NAME(), CURRENT_ACCOUNT_NAME(), USER_NAME)), 256)),
      'credits_used', CREDITS_USED,
      'credits_used_compute', CREDITS_USED_COMPUTE,
      'credits_used_cloud_services', CREDITS_USED_CLOUD_SERVICES,
      'query_start_time', QUERY_START_TIME,
      'query_end_time', QUERY_END_TIME
    ) AS EVIDENCE
  FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_METERING_HISTORY
  WHERE QUERY_METERING_HOUR < TO_TIMESTAMP_TZ('__WINDOW_END_UTC__')
    AND DATEADD('hour', 1, QUERY_METERING_HOUR) > TO_TIMESTAMP_TZ('__WINDOW_START_UTC__')
  ORDER BY QUERY_METERING_HOUR, QUERY_ID
  LIMIT 5000
), execution_context AS (
  SELECT OBJECT_CONSTRUCT_KEEP_NULL(
    '_dataset', 'execution_context',
    'observed_at', CURRENT_TIMESTAMP(),
    'account_identifier_sha256', SHA2(TO_JSON(ARRAY_CONSTRUCT(CURRENT_ORGANIZATION_NAME(), CURRENT_ACCOUNT_NAME())), 256),
    'collector_user_sha256', SHA2(TO_JSON(ARRAY_CONSTRUCT(CURRENT_ORGANIZATION_NAME(), CURRENT_ACCOUNT_NAME(), CURRENT_USER())), 256),
    'primary_role_sha256', SHA2(TO_JSON(ARRAY_CONSTRUCT(CURRENT_ORGANIZATION_NAME(), CURRENT_ACCOUNT_NAME(), CURRENT_ROLE())), 256),
    'primary_role_type', CURRENT_ROLE_TYPE(),
    'secondary_roles_sha256', SHA2(TO_JSON(ARRAY_CONSTRUCT(CURRENT_ORGANIZATION_NAME(), CURRENT_ACCOUNT_NAME(), CURRENT_SECONDARY_ROLES())), 256),
    'session_timezone', IFF(TO_CHAR(CURRENT_TIMESTAMP(), 'TZH:TZM') = '+00:00', 'UTC', TO_CHAR(CURRENT_TIMESTAMP(), 'TZH:TZM'))
  ) AS EVIDENCE
)
SELECT EVIDENCE FROM (
  SELECT 0 AS SORT_GROUP, '' AS SORT_KEY, EVIDENCE FROM execution_context
  UNION ALL SELECT 1, SORT_KEY, EVIDENCE FROM usage_rows
)
ORDER BY SORT_GROUP, SORT_KEY;
