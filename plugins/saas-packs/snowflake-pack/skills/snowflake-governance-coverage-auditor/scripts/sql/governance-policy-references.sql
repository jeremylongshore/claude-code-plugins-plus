-- Historical attachment inventory for the policy kinds documented by this
-- Account Usage view. Collect join attachments with bounded, current
-- Information Schema POLICY_REFERENCES calls instead.
SELECT
  'asset_' || LOWER(SHA2(UPPER(CONCAT_WS('|', REF_ENTITY_DOMAIN, REF_DATABASE_NAME, REF_SCHEMA_NAME, REF_ENTITY_NAME, COALESCE(REF_COLUMN_NAME, ''))), 256)) AS asset_key,
  'policy_' || LOWER(SHA2(UPPER(CONCAT_WS('|', POLICY_DB, POLICY_SCHEMA, POLICY_NAME)), 256)) AS policy_key,
  POLICY_KIND,
  IFF(TAG_NAME IS NULL, 'DIRECT', 'TAG') AS assignment,
  POLICY_STATUS,
  IFF(
    POLICY_KIND = 'AGGREGATION_POLICY' AND REF_ARG_COLUMN_NAMES IS NOT NULL,
    'sha256:' || LOWER(SHA2(UPPER(REF_ARG_COLUMN_NAMES), 256)),
    NULL
  ) AS entity_key_hash
FROM SNOWFLAKE.ACCOUNT_USAGE.POLICY_REFERENCES
WHERE REF_DATABASE_NAME = '__DATABASE_LITERAL__'
  AND POLICY_KIND IN ('MASKING_POLICY', 'ROW_ACCESS_POLICY', 'PROJECTION_POLICY', 'AGGREGATION_POLICY')
ORDER BY asset_key, POLICY_KIND, policy_key
LIMIT __ROW_LIMIT_PLUS_ONE__;
