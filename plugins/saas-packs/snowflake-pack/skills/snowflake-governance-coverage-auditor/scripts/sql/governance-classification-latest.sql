-- RESULT is flattened only to derive opaque column identities. Classification
-- details, category/tag values, RESULT, and ERROR_MESSAGE are not exported.
WITH latest AS (
  SELECT l.DATABASE_NAME, l.SCHEMA_NAME, l.TABLE_NAME, l.RESULT, l.STATUS,
    l.LAST_CLASSIFIED_ON, l.LAST_CLASSIFICATION_ATTEMPT, l.ERROR_MESSAGE,
    IFF(t.TABLE_TYPE ILIKE '%VIEW', 'VIEW', 'TABLE') AS object_domain
  FROM SNOWFLAKE.ACCOUNT_USAGE.DATA_CLASSIFICATION_LATEST l
  LEFT JOIN SNOWFLAKE.ACCOUNT_USAGE.TABLES t ON t.TABLE_ID = l.TABLE_ID AND t.DELETED IS NULL
  WHERE l.DATABASE_NAME = '__DATABASE_LITERAL__'
), classified_assets AS (
  SELECT
    'asset_' || LOWER(SHA2(UPPER(CONCAT_WS('|', COALESCE(object_domain, 'TABLE'), DATABASE_NAME, SCHEMA_NAME, TABLE_NAME, '')), 256)) AS asset_key,
    STATUS, LAST_CLASSIFIED_ON, LAST_CLASSIFICATION_ATTEMPT, ERROR_MESSAGE
  FROM latest

  UNION ALL

  SELECT
    'asset_' || LOWER(SHA2(UPPER(CONCAT_WS('|', 'COLUMN', DATABASE_NAME, SCHEMA_NAME, TABLE_NAME, c.key::STRING)), 256)) AS asset_key,
    STATUS, LAST_CLASSIFIED_ON, LAST_CLASSIFICATION_ATTEMPT, ERROR_MESSAGE
  FROM latest, LATERAL FLATTEN(INPUT => RESULT) c
)
SELECT
  asset_key,
  STATUS,
  LAST_CLASSIFIED_ON,
  LAST_CLASSIFICATION_ATTEMPT AS last_attempt_on,
  (ERROR_MESSAGE IS NOT NULL) AS error_present
FROM classified_assets
ORDER BY asset_key
LIMIT __ROW_LIMIT_PLUS_ONE__;
