#!/usr/bin/env node
/**
 * fetch-github-stats.mjs — pull the star count for this repository.
 *
 * WHY THIS EXISTS
 * ---------------
 * The rebuilt homepage prints the star count as a credibility line next to the
 * version. A hardcoded number is a lie with a delay on it: it is correct the day
 * it ships and quietly wrong every day after. Every other number on that page
 * (skills, plugins, agents, installs) is already build-time data, so the star
 * count is the only one that would rot — this closes that gap.
 *
 * SOURCE OF TRUTH
 * ---------------
 * The public REST endpoint, unauthenticated:
 *   https://api.github.com/repos/<owner>/<repo>  ->  { stargazers_count }
 *
 * Unauthenticated is deliberate. The workflow that runs this has a token, but
 * the number is public data and the anonymous rate limit (60/hr/IP) is two
 * orders of magnitude above a once-daily job. Not passing a token means this
 * script cannot leak one.
 *
 * FAILS SOFT ON PURPOSE
 * ---------------------
 * Mirrors fetch-skills-stats.mjs exactly: on any failure it leaves the existing
 * data file untouched and exits 0. The page renders the last known good value,
 * or omits the line entirely if there has never been one. A GitHub blip must
 * never break a site build.
 */

import { writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, '..');
const OUT = join(REPO_ROOT, 'marketplace', 'src', 'data', 'github-stats.json');

const OWNER = 'jeremylongshore';
const REPO = 'claude-code-plugins-plus-skills';
const API = `https://api.github.com/repos/${OWNER}/${REPO}`;

async function fetchJson(url, ms = 20_000) {
  const ac = new AbortController();
  const t = setTimeout(() => ac.abort(), ms);
  try {
    const r = await fetch(url, {
      signal: ac.signal,
      headers: {
        accept: 'application/vnd.github+json',
        'user-agent': 'ccpi-stats/1.0',
      },
    });
    if (!r.ok) throw new Error(`HTTP ${r.status}`);
    return await r.json();
  } finally {
    clearTimeout(t);
  }
}

async function main() {
  let data;
  try {
    data = await fetchJson(API);
  } catch (e) {
    console.error(`  github api fetch failed: ${e.message} — leaving existing data untouched`);
    process.exit(0); // fail soft: never break the build
  }

  const stars = Number.parseInt(String(data?.stargazers_count), 10);
  const forks = Number.parseInt(String(data?.forks_count), 10);
  if (!Number.isSafeInteger(stars) || stars <= 0) {
    console.error(`  refusing to write a non-integer star count: ${data?.stargazers_count}`);
    process.exit(0);
  }

  // Sanity guard, not a monotonic one. Stars CAN legitimately fall — people
  // unstar — so a small decline is real and must be allowed through. A >20%
  // collapse overnight is not a real event; it is a parse or an API shape
  // change, and shipping it would put a false number on the homepage.
  // Read-then-catch rather than existsSync-then-read: the check-then-act pair
  // is a TOCTOU race (CodeQL js/file-system-race), and a missing file is simply
  // "no previous value", which the catch already models.
  try {
    const prev = JSON.parse(readFileSync(OUT, 'utf8'));
    if (typeof prev.stars === 'number' && stars < prev.stars * 0.8) {
      console.error(
        `  refusing update: ${prev.stars} -> ${stars} is a >20% collapse, which ` +
          `indicates a bad read rather than reality.`,
      );
      process.exit(0);
    }
  } catch {
    /* absent or unreadable previous file is not a reason to fail */
  }

  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(
    OUT,
    JSON.stringify(
      {
        $comment:
          'Generated by scripts/fetch-github-stats.mjs. Star count for the homepage credibility line — refreshed daily so the number on the page is never stale.',
        source: `https://github.com/${OWNER}/${REPO}`,
        generatedAt: new Date().toISOString(),
        stars,
        starsDisplay: stars.toLocaleString('en-US'),
        forks: Number.isSafeInteger(forks) && forks > 0 ? forks : undefined,
      },
      null,
      2,
    ) + '\n',
  );
  console.log(`  github stars: ${stars} -> ${OUT}`);
}

await main();
