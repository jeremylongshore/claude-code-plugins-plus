import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

import {
  assertGeneratedContentCurrent,
  readIndexedArtifact,
} from './check-generated-artifacts.mjs';

const CHECKER = fileURLToPath(new URL('./check-generated-artifacts.mjs', import.meta.url));

function fixture() {
  const root = mkdtempSync(join(tmpdir(), 'generated-artifacts-'));
  execFileSync('git', ['init', '-q'], { cwd: root });
  return root;
}

function run(root) {
  return spawnSync(process.execPath, [CHECKER], {
    cwd: root,
    encoding: 'utf8',
  });
}

test('untracked marketplace build projections are accepted', (t) => {
  const root = fixture();
  t.after(() => rmSync(root, { recursive: true, force: true }));

  for (const name of ['jrig-data.json', 'readme-sections.json']) {
    const path = join(root, 'marketplace', 'src', 'data', name);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, '{}\n');
  }

  const result = run(root);
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /0 tracked/);
});

for (const name of ['jrig-data.json', 'readme-sections.json']) {
  test(`tracked ${name} is refused`, (t) => {
    const root = fixture();
    t.after(() => rmSync(root, { recursive: true, force: true }));
    const relative = `marketplace/src/data/${name}`;
    const path = join(root, relative);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, '{}\n');
    execFileSync('git', ['add', relative], { cwd: root });

    const result = run(root);
    assert.equal(result.status, 1);
    assert.match(result.stderr, new RegExp(`${name.replace('.', '\\.')}`));
    assert.match(result.stderr, /GENERATED projection/);
  });
}

test('Git enumeration failure refuses instead of passing an empty set', (t) => {
  const root = mkdtempSync(join(tmpdir(), 'generated-artifacts-no-git-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));

  const result = run(root);
  assert.equal(result.status, 1);
  assert.match(result.stderr, /refuses to pass without Git evidence/);
});

test('rendered generated bytes are compared to the Git index without touching the worktree', (t) => {
  const root = fixture();
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const relative = 'marketplace/src/data/skills-index.json';
  const path = join(root, relative);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, '{"state":"indexed"}\n');
  execFileSync('git', ['add', relative], { cwd: root });
  writeFileSync(path, '{"state":"unstaged-author-work"}\n');

  assert.equal(readIndexedArtifact(relative, { root }).toString(), '{"state":"indexed"}\n');
  assert.deepEqual(
    assertGeneratedContentCurrent([{ path: relative, contents: '{"state":"indexed"}\n' }], {
      root,
    }),
    [relative],
  );
  assert.equal(readFileSync(path, 'utf8'), '{"state":"unstaged-author-work"}\n');
});

test('a deliberately mutated indexed artifact is refused by regenerated bytes', (t) => {
  const root = fixture();
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const relative = 'marketplace/src/data/skills-index.json';
  const path = join(root, relative);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, '{"count":3067}\n');
  execFileSync('git', ['add', relative], { cwd: root });

  assert.throws(
    () =>
      assertGeneratedContentCurrent([{ path: relative, contents: '{"count":3068}\n' }], { root }),
    /generated content drift.*skills-index\.json/,
  );
});

test('one drifted full catalog is refused when the metadata index still matches', (t) => {
  const root = fixture();
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const index = 'marketplace/src/data/skills-index.json';
  const catalog = 'marketplace/src/data/skills-catalog.json';
  for (const [relative, contents] of [
    [index, '{"count":3068}\n'],
    [catalog, '{"count":3067}\n'],
  ]) {
    const path = join(root, relative);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, contents);
    execFileSync('git', ['add', relative], { cwd: root });
  }

  assert.throws(
    () =>
      assertGeneratedContentCurrent(
        [
          { path: index, contents: '{"count":3068}\n' },
          { path: catalog, contents: '{"count":3068}\n' },
        ],
        { root },
      ),
    /generated content drift.*skills-catalog\.json/,
  );
});

test('content checks fail closed on untracked, symlinked, duplicate, and escaping paths', (t) => {
  const root = fixture();
  t.after(() => rmSync(root, { recursive: true, force: true }));
  assert.throws(
    () => assertGeneratedContentCurrent([{ path: 'untracked.json', contents: '{}' }], { root }),
    /regular stage-0 index entry/,
  );
  assert.throws(
    () => assertGeneratedContentCurrent([{ path: '../escape.json', contents: '{}' }], { root }),
    /escapes repository/,
  );

  writeFileSync(join(root, 'target.json'), '{}\n');
  symlinkSync('target.json', join(root, 'link.json'));
  execFileSync('git', ['add', 'link.json'], { cwd: root });
  assert.throws(
    () => assertGeneratedContentCurrent([{ path: 'link.json', contents: '{}' }], { root }),
    /regular stage-0 index entry/,
  );

  writeFileSync(join(root, 'tracked.json'), '{}\n');
  execFileSync('git', ['add', 'tracked.json'], { cwd: root });
  assert.throws(
    () =>
      assertGeneratedContentCurrent(
        [
          { path: 'tracked.json', contents: '{}\n' },
          { path: 'tracked.json', contents: '{}\n' },
        ],
        { root },
      ),
    /duplicate generated content candidate/,
  );
});
